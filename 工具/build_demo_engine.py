"""Build the demo's Python archive from the same sources as the slicer plug-ins."""
import argparse
import base64
import gzip
import hashlib
import io
import json
import sys
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo

ROOT = Path(__file__).resolve().parents[1]
DEMO = ROOT / "demo"
TOOLS = ROOT / "工具"


def archive():
    buffer = io.BytesIO()
    with ZipFile(buffer, "w") as file:
        sources = [TOOLS / (name + ".py") for name in (
            "automatic_curve", "gcode_feature_times", "gcode_input", "infill_speed_smoothing",
            "layer_time_smoothing", "layer_uniformity", "slicer_postprocess")]
        for path in [*sources, DEMO / "smooth_bridge.py"]:
            file.writestr(ZipInfo(path.name), path.read_text("utf8").encode(), compress_type=ZIP_DEFLATED)
    packed = base64.b64encode(buffer.getvalue()).decode("ascii")
    planner = (ROOT / "集成/Orca/orca_layer_smoothing/planner.js").read_text("utf8")
    (DEMO / "smooth-package.js").write_text(
        "// Generated by 工具/build_demo_engine.py from the repository sources.\n"
        'globalThis.layerSmoothingPackage = "' + packed + '";\n' + planner, encoding="utf8", newline="\n")


def cache_example(path):
    sys.path[:0] = [str(TOOLS), str(DEMO)]
    from smooth_bridge import Preview
    source = Path(path).read_bytes()
    view = Preview(source)
    summary = view.calculate(None)
    blob = gzip.compress(view.output, compresslevel=9, mtime=0) if summary["changed"] else b""
    cache = dict(result=summary, basis=view.planning_inputs(), sha256=hashlib.sha256(source).hexdigest(),
                 gzip=base64.b64encode(blob).decode("ascii"))
    (DEMO / "smooth-example.js").write_text(
        "// Generated from the distributed Voron G-code by 工具/build_demo_engine.py.\n"
        "globalThis.layerSmoothingExample=" + json.dumps(cache, separators=(",", ":"), allow_nan=False) +
        ";\n", encoding="utf8", newline="\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--example", type=Path, help="recalculate cached auto export from the published Voron G-code")
    args = parser.parse_args()
    archive()
    if args.example:
        cache_example(args.example)
